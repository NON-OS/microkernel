class GenError(Exception):
    pass


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def read(root, rel):
    return (root / rel).read_text()


# Capability bits: `Name = 1 << N,` inside `capability_table! { ... }`.
def capability_bits(root):
    body = strip_comments(read(root, CAP_DEFS))
    body = re.sub(r"#\[[^\]]*\]", "", body)
    caps = re.findall(r"\b([A-Z][A-Za-z0-9]*)\s*=\s*1\s*<<\s*(\d+)\s*,", body)
    if not caps:
        raise GenError("no capability bits found in " + CAP_DEFS)
    seen_bits = set()
    seen_names = set()
    out = []
    for name, bit in caps:
        bit = int(bit)
        if bit >= 64:
            raise GenError(f"capability {name} has bit {bit}, outside a u64")
        if bit in seen_bits or name in seen_names:
            raise GenError(f"capability {name} bit {bit} is not unique")
        seen_bits.add(bit)
        seen_names.add(name)
        out.append((name, bit))
    return out


# Syscall numbers: `Name = crate::syscall::abi::tag4(b"ABCD"),`.
def syscall_numbers(root):
    body = strip_comments(read(root, SYSCALL_DEFS))
    entries = re.findall(r"\b([A-Z][A-Za-z0-9]*)\s*=\s*crate::syscall::abi::tag4\(b\"(.{4})\"\)", body)
    if not entries:
        raise GenError("no syscall numbers found in " + SYSCALL_DEFS)
    out = []
    seen = set()
    for name, tag in entries:
        b = tag.encode("ascii")
        value = b[0] | (b[1] << 8) | (b[2] << 16) | (b[3] << 24)
        if value in seen:
            raise GenError(f"syscall {name} number {value:#x} is not unique")
        seen.add(value)
        out.append((name, tag, value))
    return out


# Syscalls the ABI registry resolves (`SyscallNumber::from_u64`).
def abi_registered(root):
    names = set()
    for path in sorted((root / ABI_REGISTRY).glob("*.rs")):
        for name in re.findall(r"SyscallNumber::([A-Za-z0-9]+)", strip_comments(path.read_text())):
            names.add(name)
    return names


# A small parser for the boolean expressions the checks are written in.
TOKEN = re.compile(
    r"\s*(?:(&&)|(\|\|)|(!)|(\()|(\))|(true\b)|(false\b)|(launcher\b)"
    r"|(?:caps|self)\.grants_all\(&\[([^\]]*)\]\)"
    r"|(?:caps|self)\.grants\(Capability::([A-Za-z0-9]+)\)"
    r"|(?:caps|self)\.([a-z_][a-z0-9_]*)\(\))"
)


def tokenize(expr):
    pos = 0
    toks = []
    expr = expr.strip()
    while pos < len(expr):
        m = TOKEN.match(expr, pos)
        if not m or m.end() == pos:
            raise GenError(f"cannot read check expression at: {expr[pos:pos + 60]!r}")
        pos = m.end()
        g = m.groups()
        if g[0]:
            toks.append(("and",))
        elif g[1]:
            toks.append(("or",))
        elif g[2]:
            toks.append(("not",))
        elif g[3]:
            toks.append(("(",))
        elif g[4]:
            toks.append((")",))
        elif g[5]:
            toks.append(("yes",))
        elif g[6]:
            toks.append(("no",))
        elif g[7]:
            toks.append(("launcher",))
        elif g[8] is not None:
            names = [n.strip() for n in g[8].split(",") if n.strip()]
            caps = []
            for n in names:
                mm = re.fullmatch(r"Capability::([A-Za-z0-9]+)", n)
                if not mm:
                    raise GenError(f"cannot read grants_all entry {n!r}")
                caps.append(mm.group(1))
            toks.append(("all", caps))
        elif g[9]:
            toks.append(("has", g[9]))
        elif g[10]:
            toks.append(("method", g[10]))
    return toks


class Parser:
    def __init__(self, toks, methods, stack):
        self.toks = toks
        self.i = 0
        self.methods = methods
        self.stack = stack

    def peek(self):
        return self.toks[self.i] if self.i < len(self.toks) else None

    def take(self):
        t = self.peek()
        self.i += 1
        return t

    def parse(self):
        e = self.disj()
        if self.peek() is not None:
            raise GenError(f"trailing tokens in check expression: {self.toks[self.i:]}")
        return e

    def disj(self):
        e = self.conj()
        while self.peek() == ("or",):
            self.take()
            e = ("or", e, self.conj())
        return e

    def conj(self):
        e = self.unary()
        while self.peek() == ("and",):
            self.take()
            e = ("and", e, self.unary())
        return e

    def unary(self):
        t = self.take()
        if t is None:
            raise GenError("check expression ends early")
        kind = t[0]
        if kind == "not":
            return ("not", self.unary())
        if kind == "(":
            e = self.disj()
            if self.take() != (")",):
                raise GenError("unbalanced parenthesis in check expression")
            return e
        if kind == "yes":
            return ("yes",)
        if kind == "no":
            return ("not", ("yes",))
        if kind == "launcher":
            return ("launcher",)
        if kind == "has":
            return ("has", t[1])
        if kind == "all":
            if not t[1]:
                raise GenError("empty grants_all")
            e = ("has", t[1][0])
            for c in t[1][1:]:
                e = ("and", e, ("has", c))
            return e
        if kind == "method":
            name = t[1]
            if name == "is_valid":
                return ("valid",)
            return expand_method(name, self.methods, self.stack)
        raise GenError(f"unexpected token {t}")


def expand_method(name, methods, stack):
    if name not in methods:
        raise GenError(f"check method {name} is not defined in {CHECKS_DIR} or {AUTHORITY}")
    if name in stack:
        raise GenError(f"check method {name} is recursive")
    return Parser(tokenize(methods[name]), methods, stack + [name]).parse()


# `fn name(&self) -> bool { expr }` in the token check impls.
def check_methods(root):
    methods = {}
    paths = sorted((root / CHECKS_DIR).glob("*.rs")) + [root / a for a in AUTHORITY]
    for path in paths:
        text = strip_comments(path.read_text())
        for name, body in re.findall(
            r"fn\s+([a-z_][a-z0-9_]*)\s*\(&self\)\s*->\s*bool\s*\{(.*?)\}", text, flags=re.S
        ):
            if name in methods:
                raise GenError(f"check method {name} defined twice")
            methods[name] = " ".join(body.split())
    if not methods:
        raise GenError("no check methods found in " + CHECKS_DIR)
    return methods


# The order `cap_table::is_allowed` consults the groups in; the first group
# that claims a number decides it.
def table_order(root):
    text = strip_comments(read(root, CAP_TABLE_DIR + "/mod.rs"))
    m = re.search(r"fn\s+is_allowed\b.*?\{(.*)\}", text, flags=re.S)
    if not m:
        raise GenError("is_allowed not found in cap_table/mod.rs")
    order = re.findall(r"\b([a-z_][a-z0-9_]*)::check\(", m.group(1))
    if not order:
        raise GenError("is_allowed consults no group")
    if not re.search(r"\.unwrap_or\(false\)\s*$", m.group(1).strip()):
        raise GenError("is_allowed no longer defaults an unclaimed number to false")
    return order


def split_arms(match_body):
    arms = []
    depth = 0
    cur = ""
    for ch in match_body:
        if ch in "({[":
            depth += 1
        elif ch in ")}]":
            depth -= 1
        if ch == "," and depth == 0:
            arms.append(cur)
            cur = ""
        elif ch == "}" and depth == 0 and "=>" in cur and cur.split("=>", 1)[1].strip().startswith("{"):
            # A block-bodied arm ends at its closing brace, with no comma.
            arms.append(cur + ch)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        arms.append(cur)
    return [a.strip() for a in arms if a.strip()]


def group_arms(root, group, methods):
    text = strip_comments(read(root, f"{CAP_TABLE_DIR}/{group}.rs"))
    fn = re.search(r"pub\(super\)\s+fn\s+check\s*\((.*?)\)\s*->\s*Option<bool>\s*\{(.*)\}\s*$", text, flags=re.S)
    if not fn:
        raise GenError(f"{group}.rs: check signature not recognised")
    body = fn.group(2)
    # The graphics form: refuse an invalid token, then name one capability.
    guard = re.match(r"\s*if\s+!caps\.is_valid\(\)\s*\{\s*return\s+Some\(false\);\s*\}\s*let\s+required\s*=\s*match\s+number\s*\{(.*)\};\s*Some\(caps\.grants\(required\)\)\s*$", body, flags=re.S)
    if guard:
        out = []
        for arm in split_arms(guard.group(1)):
            lhs, rhs = [x.strip() for x in arm.split("=>", 1)]
            if lhs == "_":
                if rhs != "return None":
                    raise GenError(f"{group}.rs: default arm is not `return None`")
                continue
            cap = re.fullmatch(r"Capability::([A-Za-z0-9]+)", rhs)
            if not cap:
                raise GenError(f"{group}.rs: cannot read arm {arm!r}")
            for name in re.findall(r"SyscallNumber::([A-Za-z0-9]+)", lhs):
                out.append((name, ("and", ("valid",), ("has", cap.group(1)))))
        return out
    m = re.match(r"\s*Some\(match\s+number\s*\{(.*)\}\)\s*$", body, flags=re.S)
    if not m:
        raise GenError(f"{group}.rs: body is not `Some(match number {{ .. }})`")
    out = []
    saw_default = False
    for arm in split_arms(m.group(1)):
        lhs, rhs = [x.strip() for x in arm.split("=>", 1)]
        rhs = rhs.strip()
        if rhs.startswith("{") and rhs.endswith("}"):
            rhs = rhs[1:-1].strip()
        if lhs == "_":
            if rhs != "return None":
                raise GenError(f"{group}.rs: default arm is not `return None`")
            saw_default = True
            continue
        names = re.findall(r"SyscallNumber::([A-Za-z0-9]+)", lhs)
        if not names or re.sub(r"SyscallNumber::[A-Za-z0-9]+|\|", "", lhs).strip():
            raise GenError(f"{group}.rs: cannot read pattern {lhs!r}")
        req = Parser(tokenize(rhs), methods, []).parse()
        for name in names:
            out.append((name, req))
    if not saw_default:
        raise GenError(f"{group}.rs: no `_ => return None` arm")
    return out


def syscall_table(root, methods):
    claimed = {}
    for group in table_order(root):
        for name, req in group_arms(root, group, methods):
            if name not in claimed:
                claimed[name] = (group, req)
    return claimed


def signature_policy(root):
    text = strip_comments(read(root, POLICY))
    m = re.search(r"NONOS_PRODUCTION_POLICY\s*:\s*SignaturePolicy<'static>\s*=\s*SignaturePolicy\s*\{\s*required:\s*&\[([^\]]*)\]", text)
    if not m:
        raise GenError("NONOS_PRODUCTION_POLICY not found in " + POLICY)
    algs = re.findall(r"AlgId::([A-Za-z0-9]+)", m.group(1))
    ids = dict(
        (n, int(v, 0))
        for n, v in re.findall(r"\b([A-Z][A-Za-z0-9]*)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*,", strip_comments(read(root, ALG_IDS)))
    )
    out = []
    for a in algs:
        if a not in ids:
            raise GenError(f"policy names unknown algorithm {a}")
        out.append((a, ids[a]))
    if not out:
        raise GenError("the production signature policy requires no algorithm")
    return out


def lean_req(req, cap_index):
    kind = req[0]
    if kind == "yes":
        return ".yes"
    if kind == "valid":
        return ".valid"
    if kind == "launcher":
        return ".launcher"
    if kind == "has":
        if req[1] not in cap_index:
            raise GenError(f"unknown capability {req[1]}")
        return f"(.has {cap_index[req[1]]})"
    if kind == "not":
        return f"(.not {lean_req(req[1], cap_index)})"
    if kind in ("and", "or"):
        return f"(.{kind} {lean_req(req[1], cap_index)} {lean_req(req[2], cap_index)})"
    raise GenError(f"unknown requirement {req}")


def render_caps(caps):
    lines = [HEADER.format(sources=CAP_DEFS)]
    lines.append("namespace Formal.Data\n")
    lines.append("/-- Every capability, as (name, bit index): `Capability::X.bit() = 1 << index`. -/")
    lines.append("def capabilityBits : List (String × Nat) := [")
    body = [f'  ("{n}", {b})' for n, b in caps]
    lines.append(",\n".join(body))
    lines.append("]\n")
    for n, b in caps:
        lines.append(f"/-- `Capability::{n}`. -/")
        lines.append(f"def cap{n} : Nat := {b}")
    lines.append(f"\n/-- The number of capabilities the kernel defines. -/")
    lines.append(f"def capabilityCount : Nat := {len(caps)}\n")
    lines.append("end Formal.Data\n")
    return "\n".join(lines)


def render_syscalls(numbers, registered, claimed, cap_index):
    lines = [HEADER.format(sources=", ".join([SYSCALL_DEFS, ABI_REGISTRY + "/", CHECKS_DIR + "/", CAP_TABLE_DIR + "/"] + AUTHORITY))]
    lines.append("import Formal.Req\n")
    lines.append("namespace Formal.Data\n")
    lines.append("open Formal\n")
    lines.append("/-- Every syscall the ABI registry resolves: (number, tag, name). A number")
    lines.append("    outside this list is ENOSYS before any check runs. -/")
    lines.append("def abiSyscalls : List (Nat × String × String) := [")
    rows = []
    for name, tag, value in numbers:
        if name in registered:
            rows.append(f'  ({value}, "{tag}", "{name}")')
    lines.append(",\n".join(rows))
    lines.append("]\n")
    lines.append("/-- `cap_table::is_allowed` as data: (number, requirement) for every number")
    lines.append("    a group claims, in the order the groups are consulted. A number no group")
    lines.append("    claims is refused (`unwrap_or(false)`). -/")
    lines.append("def capTable : List (Nat × Req) := [")
    rows = []
    for name, tag, value in numbers:
        if name in claimed:
            group, req = claimed[name]
            rows.append(f"  ({value}, {lean_req(req, cap_index)}) -- {name} ({group})")
    # Lean list syntax: separators before the trailing comment.
    out_rows = []
    for i, r in enumerate(rows):
        code, comment = r.split(" -- ", 1)
        sep = "," if i + 1 < len(rows) else ""
        out_rows.append(f"{code}{sep} -- {comment}")
    lines.append("\n".join(out_rows))
    lines.append("]\n")
    lines.append("-- Each ABI syscall number by name, for the handlers the model gives an effect.")
    for name, tag, value in numbers:
        if name in registered:
            lines.append(f"def sys{name} : Nat := {value} -- {tag}")
    lines.append("")
    lines.append(f"/-- Syscalls in the ABI: {sum(1 for n in numbers if n[0] in registered)}; claimed by the table: {len(rows)}. -/")
    lines.append(f"def abiCount : Nat := {sum(1 for n in numbers if n[0] in registered)}")
    lines.append(f"def claimedCount : Nat := {len(rows)}\n")
    lines.append("end Formal.Data\n")
    return "\n".join(lines)


def render_policy(policy):
    lines = [HEADER.format(sources=", ".join([POLICY, ALG_IDS]))]
    lines.append("namespace Formal.Data\n")
    lines.append("/-- `NONOS_PRODUCTION_POLICY.required`: every algorithm a manifest must carry")
    lines.append("    a verifying publisher signature for, as (name, `AlgId` value). -/")
    lines.append("def requiredSignatures : List (String × Nat) := [")
    lines.append(",\n".join(f'  ("{n}", {v})' for n, v in policy))
    lines.append("]\n")
    lines.append("end Formal.Data\n")
    return "\n".join(lines)


def generate(root):
    caps = capability_bits(root)
    cap_index = dict(caps)
    numbers = syscall_numbers(root)
    registered = abi_registered(root)
    known = {n for n, _, _ in numbers}
    unknown = registered - known
    if unknown:
        raise GenError(f"ABI registry names unknown syscalls: {sorted(unknown)}")
    methods = check_methods(root)
    claimed = syscall_table(root, methods)
    stray = set(claimed) - known
    if stray:
        raise GenError(f"cap_table names unknown syscalls: {sorted(stray)}")
    return {
        "CapBits.lean": render_caps(caps),
        "Syscalls.lean": render_syscalls(numbers, registered, claimed, cap_index),
        "Policy.lean": render_policy(signature_policy(root)),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[2]))
    args = ap.parse_args()
    root = pathlib.Path(args.root)
    try:
        files = generate(root)
    except GenError as e:
        print(f"gen_tables: {e}", file=sys.stderr)
        return 2
    out = root / OUT_DIR
    drift = []
    for name, text in files.items():
        path = out / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                drift.append(str(path.relative_to(root)))
        else:
            out.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if drift:
        print("gen_tables: generated data differs from the source; run formal/scripts/gen_tables.py", file=sys.stderr)
        for d in drift:
            print(f"  {d}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
