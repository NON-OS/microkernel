//! A small seeded generator, so a sweep is the same on every machine.

pub struct Regs(u64);

impl Regs {
    pub fn new(seed: u64) -> Self {
        Self(seed)
    }

    pub fn any(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }

    pub fn below(&mut self, n: usize) -> usize {
        (self.any() % n as u64) as usize
    }
}
