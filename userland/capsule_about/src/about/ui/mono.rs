//! What the shared text helpers leave to the app: bytes as the `&str` they
//! take.

/// The bytes as text, or nothing when they are not UTF-8.
pub fn valid(bytes: &[u8]) -> &str {
    core::str::from_utf8(bytes).unwrap_or("")
}
