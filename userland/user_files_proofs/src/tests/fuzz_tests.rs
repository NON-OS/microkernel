//! The fuzz target's input, run here over generated bytes: random, and
//! valid requests with bytes flipped.

use nonos_user_files::limits::DEFAULT_QUOTA;
use nonos_user_files::manifest::{decode, encode};
use nonos_user_files::Broker;

use super::{fresh, pattern, put_file};
use crate::doubles::{Desk, Volume};
use crate::fuzz_input::{run, FUZZ_PID};
use crate::rng::Rng;

fn populated() -> (Broker<Volume>, Desk) {
    let (mut b, desk) = fresh();
    put_file(&mut b, &desk, b"Documents/a", &pattern(1, 2_000_000));
    put_file(&mut b, &desk, b"Downloads/b", b"b");
    (b, desk)
}

#[test]
fn random_bytes_never_panic_the_broker() {
    let (mut b, desk) = populated();
    let mut rng = Rng(0x5eed_f00d);
    for _ in 0..20_000 {
        let n = rng.below(300) as usize;
        run(&mut b, &desk, &rng.bytes(n));
    }
    let _ = FUZZ_PID;
}

#[test]
fn flipped_requests_never_panic_the_broker() {
    let (mut b, desk) = populated();
    let mut rng = Rng(0xdead_beef);
    let paths: [&[u8]; 3] = [b"Documents/a", b"Downloads/b", b"Documents/new"];
    for i in 0..20_000u64 {
        let op = (i % 17) as u16;
        let path = paths[(i % 3) as usize];
        let n = (rng.below(4) * 8) as usize;
        let mut body = rng.bytes(n);
        body.extend_from_slice(path);
        let mut msg = Vec::new();
        msg.extend_from_slice(&u32::from_le_bytes(*b"NOUF").to_le_bytes());
        msg.extend_from_slice(&1u16.to_le_bytes());
        msg.extend_from_slice(&op.to_le_bytes());
        msg.extend_from_slice(&(i as u32).to_le_bytes());
        msg.extend_from_slice(&(body.len() as u32).to_le_bytes());
        msg.extend_from_slice(&body);
        if rng.below(3) == 0 {
            let at = rng.below(msg.len() as u64) as usize;
            msg[at] ^= 1 << rng.below(8);
        }
        run(&mut b, &desk, &msg);
    }
}

#[test]
fn a_manifest_decodes_only_whole_and_true() {
    let (mut b, desk) = populated();
    let _ = Broker::new(Volume::default(), DEFAULT_QUOTA);
    let v = b.objects().reboot();
    let newest = [0u64, 1]
        .iter()
        .filter_map(|id| v.objects.get(id))
        .filter_map(|s| nonos_user_files::manifest::Slot::decode(s))
        .max_by_key(|s| s.generation)
        .unwrap();
    let body: Vec<u8> = newest.parts.iter().flat_map(|p| v.objects[p].clone()).collect();
    let d = decode(&body).expect("the broker's own body decodes");
    assert_eq!(encode(&d.tree, d.next_id, &d.freed), body, "decode then encode is not the body");
    let mut rng = Rng(42);
    for _ in 0..5_000 {
        let mut bad = body.clone();
        let at = rng.below(bad.len() as u64) as usize;
        bad[at] ^= 1 << rng.below(8);
        if let Some(d) = decode(&bad) {
            // A flip the format cannot see (a time, a mode bit) still decodes to a tree.
            assert_eq!(encode(&d.tree, d.next_id, &d.freed), bad);
        }
        assert!(decode(&bad[..at]).is_none(), "a body cut at {at} decoded");
    }
    let _ = desk;
}
