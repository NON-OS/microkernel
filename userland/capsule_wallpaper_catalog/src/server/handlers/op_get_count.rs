use crate::catalog::count;
use crate::protocol::OP_GET_COUNT;

use super::super::respond;

pub fn handle(pid: u32) {
    let n = count().to_le_bytes();
    respond::ok(pid, OP_GET_COUNT, 0, 0, &n);
}
