//! The key codes a held Ctrl arrives with, upper and lower case.

pub(super) const CTRL_A: u32 = 0x41;
pub(super) const CTRL_C: u32 = 0x43;
pub(super) const CTRL_E: u32 = 0x45;
pub(super) const CTRL_K: u32 = 0x4B;
pub(super) const CTRL_L: u32 = 0x4C;
pub(super) const CTRL_R: u32 = 0x52;
pub(super) const CTRL_R_LO: u32 = 0x72;
pub(super) const CTRL_U: u32 = 0x55;
pub(super) const CTRL_V: u32 = 0x56;
pub(super) const CTRL_W: u32 = 0x57;
pub(super) const CTRL_A_LO: u32 = 0x61;
pub(super) const CTRL_C_LO: u32 = 0x63;
pub(super) const CTRL_E_LO: u32 = 0x65;
pub(super) const CTRL_K_LO: u32 = 0x6B;
pub(super) const CTRL_L_LO: u32 = 0x6C;
pub(super) const CTRL_U_LO: u32 = 0x75;
pub(super) const CTRL_V_LO: u32 = 0x76;
pub(super) const CTRL_W_LO: u32 = 0x77;
pub(super) const CTRL_D: u32 = 0x44;
pub(super) const CTRL_D_LO: u32 = 0x64;
pub(super) const CTRL_Y: u32 = 0x59;
pub(super) const CTRL_Y_LO: u32 = 0x79;

pub(super) const ZOOM_IN_EQ: u32 = 0x3D; // '='
pub(super) const ZOOM_IN_PLUS: u32 = 0x2B; // '+'
pub(super) const ZOOM_OUT_MINUS: u32 = 0x2D; // '-'
pub(super) const ZOOM_OUT_USCORE: u32 = 0x5F; // '_'
