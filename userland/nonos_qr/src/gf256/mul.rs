use super::tables::tables;

/// Multiply two field elements.
pub(crate) fn mul(a: u8, b: u8) -> u8 {
    if a == 0 || b == 0 {
        return 0;
    }
    let t = tables();
    let l = t.log[a as usize] as usize + t.log[b as usize] as usize;
    t.exp[l % 255]
}
