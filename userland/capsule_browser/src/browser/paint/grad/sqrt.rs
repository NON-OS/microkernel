/* Integer square root, floor(sqrt(v)), digit by digit: no floats (the
 * crate has no libm and float math is slow under emulation) and exact. */
pub(super) fn isqrt(v: u128) -> u128 {
    let mut rem = v;
    let mut root = 0u128;
    let mut bit = 1u128 << 126;
    while bit > v {
        bit >>= 2;
    }
    while bit != 0 {
        if rem >= root + bit {
            rem -= root + bit;
            root = (root >> 1) + bit;
        } else {
            root >>= 1;
        }
        bit >>= 2;
    }
    root
}
