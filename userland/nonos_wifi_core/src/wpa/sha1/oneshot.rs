//! One-shot SHA-1 of a byte string.

use super::*;

/// One-shot SHA-1 of a byte string.
pub fn sha1(data: &[u8]) -> [u8; 20] {
    let mut h = Sha1::new();
    h.update(data);
    h.finalize()
}
