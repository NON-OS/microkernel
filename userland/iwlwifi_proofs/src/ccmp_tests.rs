//! Known-answer proofs for CCMP. AES-128 is checked against the FIPS-197
//! appendix C.1 vector; AES-CCM against RFC 3610 packet vector 1. A correct CCM
//! output exercises the whole cipher (key schedule, CBC-MAC and CTR), and the
//! decrypt round-trip plus a tamper check pin the authentication.

use crate::ccmp::aes::Aes128;
use crate::ccmp::ccm::{ccm_decrypt, ccm_encrypt};
use crate::ccmp::keywrap::aes_unwrap;

#[test]
fn aes128_matches_fips197_vector() {
    let key = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f,
    ];
    let mut b = [
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee,
        0xff,
    ];
    Aes128::new(&key).encrypt_block(&mut b);
    assert_eq!(
        b,
        [
            0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4,
            0xc5, 0x5a
        ]
    );
}

#[test]
fn aes_ccm_matches_rfc3610_packet_vector_1() {
    let key = [
        0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7, 0xC8, 0xC9, 0xCA, 0xCB, 0xCC, 0xCD, 0xCE,
        0xCF,
    ];
    let nonce = [
        0x00, 0x00, 0x00, 0x03, 0x02, 0x01, 0x00, 0xA0, 0xA1, 0xA2, 0xA3, 0xA4, 0xA5,
    ];
    let aad = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07];
    let payload: [u8; 23] = [
        0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16,
        0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E,
    ];
    let expected: [u8; 31] = [
        0x58, 0x8C, 0x97, 0x9A, 0x61, 0xC6, 0x63, 0xD2, 0xF0, 0x66, 0xD0, 0xC2, 0xC0, 0xF9, 0x89,
        0x80, 0x6D, 0x5F, 0x6B, 0x61, 0xDA, 0xC3, 0x84, 0x17, 0xE8, 0xD1, 0x2C, 0xFD, 0xF9, 0x26,
        0xE0,
    ];

    let mut out = [0u8; 31];
    let n = ccm_encrypt(&key, &nonce, &aad, &payload, &mut out).unwrap();
    assert_eq!(n, 31);
    assert_eq!(out, expected, "AES-CCM encrypt matches RFC 3610");

    let mut back = [0u8; 23];
    let m = ccm_decrypt(&key, &nonce, &aad, &out, &mut back).unwrap();
    assert_eq!(m, 23);
    assert_eq!(back, payload, "decrypt recovers the payload");

    let mut bad = out;
    bad[3] ^= 0x01;
    assert!(ccm_decrypt(&key, &nonce, &aad, &bad, &mut back).is_none(), "tamper rejected");
}

#[test]
fn aes_decrypt_matches_fips197_vector() {
    let key = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f,
    ];
    let mut b = [
        0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5,
        0x5a,
    ];
    Aes128::new(&key).decrypt_block(&mut b);
    assert_eq!(
        b,
        [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff
        ]
    );
}

#[test]
fn aes_key_unwrap_matches_rfc3394_vector() {
    let kek = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E,
        0x0F,
    ];
    let wrapped = [
        0x1F, 0xA6, 0x8B, 0x0A, 0x81, 0x12, 0xB4, 0x47, 0xAE, 0xF3, 0x4B, 0xD8, 0xFB, 0x5A, 0x7B,
        0x82, 0x9D, 0x3E, 0x86, 0x23, 0x71, 0xD2, 0xCF, 0xE5,
    ];
    let mut out = [0u8; 16];
    let n = aes_unwrap(&kek, &wrapped, &mut out).unwrap();
    assert_eq!(n, 16);
    assert_eq!(
        out,
        [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB, 0xCC, 0xDD,
            0xEE, 0xFF
        ]
    );

    // a wrong KEK fails the integrity check.
    let mut bad_kek = kek;
    bad_kek[0] ^= 0x01;
    assert!(aes_unwrap(&bad_kek, &wrapped, &mut out).is_none(), "wrong KEK rejected");
}
