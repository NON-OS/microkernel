/// The order the dynamic header lists the code-length code lengths in.
pub(super) const CODE_LENGTH_ORDER: [usize; 19] =
    [16, 17, 18, 0, 8, 7, 9, 6, 10, 5, 11, 4, 12, 3, 13, 2, 14, 1, 15];

/// The fixed literal/length code of RFC 1951 section 3.2.6.
pub(super) fn fixed_lit() -> Huffman {
    let mut lengths = [0u8; 288];
    for (i, l) in lengths.iter_mut().enumerate() {
        *l = match i {
            0..=143 => 8,
            144..=255 => 9,
            256..=279 => 7,
            _ => 8,
        };
    }
    Huffman::new(&lengths)
}

/// The fixed distance code: 30 codes of length 5.
pub(super) fn fixed_dist() -> Huffman {
    Huffman::new(&[5u8; 30])
}
