//! Hex in and out, for the vector files and the known-answer text.

pub fn de(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
}

/// Upper-case hex, as the known-answer files print it; an empty field is
/// printed as `00`.
pub fn upper(b: &[u8]) -> String {
    if b.is_empty() {
        return "00".into();
    }
    b.iter().map(|x| format!("{x:02X}")).collect()
}
