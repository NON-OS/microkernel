//! Comparing byte strings without leaking where they first differ.

/// Examines every byte whatever the first says. Both callers need that: the
/// ntor auth tag, where an early exit lets a relay search for a forgery a byte
pub fn equal(left: &[u8], right: &[u8]) -> bool {
    if left.len() != right.len() {
        return false;
    }
    let mut diff = 0u8;
    for (a, b) in left.iter().zip(right.iter()) {
        diff |= a ^ b;
    }
    diff == 0
}
