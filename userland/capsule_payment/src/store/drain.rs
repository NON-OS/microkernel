use alloc::vec::Vec;

use super::types::State;

impl State {
    pub fn take_batch(&mut self, max: usize) -> Vec<Vec<u8>> {
        let take = if self.outbox.len() < max { self.outbox.len() } else { max };
        self.outbox.drain(0..take).collect()
    }
}
