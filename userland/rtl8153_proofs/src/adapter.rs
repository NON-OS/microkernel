// NONOS Operating System (AGPL-3.0-or-later)
//! An RTL8153 adapter's descriptors as these dongles commonly lay them out
//! (written here, not dumped from a device): configuration 1 the vendor
//! one, interface 0 of class FFh with bulk IN 81h, bulk OUT 02h and an
//! interrupt IN 83h, each with its SuperSpeed companion; configuration 2 a
//! CDC-ECM function on the same endpoints.

/// The device descriptor with these ids and two configurations.
pub fn device(vendor: u16, product: u16) -> [u8; 18] {
    let (v, p) = (vendor.to_le_bytes(), product.to_le_bytes());
    [0x12, 0x01, 0x10, 0x03, 0, 0, 0, 0x09, v[0], v[1], p[0], p[1], 0x00, 0x30, 1, 2, 6, 2]
}

pub const CONFIG_VENDOR: [u8; 57] = [
    0x09, 0x02, 0x39, 0x00, 0x01, 0x01, 0x00, 0xa0, 0x32, // configuration 1
    0x09, 0x04, 0x00, 0x00, 0x03, 0xff, 0xff, 0x00, 0x00, // vendor interface
    0x07, 0x05, 0x81, 0x02, 0x00, 0x04, 0x00, // bulk IN, 1024
    0x06, 0x30, 0x03, 0x00, 0x00, 0x00, // its companion, burst 4
    0x07, 0x05, 0x02, 0x02, 0x00, 0x04, 0x00, // bulk OUT, 1024
    0x06, 0x30, 0x03, 0x00, 0x00, 0x00, // its companion
    0x07, 0x05, 0x83, 0x03, 0x02, 0x00, 0x08, // interrupt IN
    0x06, 0x30, 0x00, 0x00, 0x02, 0x00, // its companion
];

pub const CONFIG_ECM: [u8; 98] = [
    0x09, 0x02, 0x62, 0x00, 0x02, 0x02, 0x00, 0xa0, 0x32, // configuration 2
    0x09, 0x04, 0x00, 0x00, 0x01, 0x02, 0x06, 0x00, 0x00, // CDC control
    0x05, 0x24, 0x00, 0x10, 0x01, // header
    0x05, 0x24, 0x06, 0x00, 0x01, // union
    0x0d, 0x24, 0x0f, 0x03, 0x00, 0x00, 0x00, 0x00, 0xea, 0x05, 0x00, 0x00, 0x00, // ethernet
    0x07, 0x05, 0x83, 0x03, 0x10, 0x00, 0x08, // interrupt IN
    0x06, 0x30, 0x00, 0x00, 0x10, 0x00, // its companion
    0x09, 0x04, 0x01, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x00, // data, off
    0x09, 0x04, 0x01, 0x01, 0x02, 0x0a, 0x00, 0x00, 0x00, // data, on
    0x07, 0x05, 0x81, 0x02, 0x00, 0x04, 0x00, // bulk IN
    0x06, 0x30, 0x03, 0x00, 0x00, 0x00, // its companion
    0x07, 0x05, 0x02, 0x02, 0x00, 0x04, 0x00, // bulk OUT
    0x06, 0x30, 0x03, 0x00, 0x00, 0x00, // its companion
];

/// The vendor configuration as a high-speed device gives it: 512-byte
/// bulk packets and no companions.
pub fn vendor_high_speed() -> Vec<u8> {
    let c = &CONFIG_VENDOR;
    let mut out = Vec::new();
    let mut at = 0;
    while at < c.len() {
        let d = &c[at..at + c[at] as usize];
        if d[1] != 0x30 {
            out.extend_from_slice(d);
        }
        at += c[at] as usize;
    }
    out[2] = out.len() as u8;
    out[22] = 0x00; // bulk IN 512
    out[23] = 0x02;
    out[29] = 0x00; // bulk OUT 512
    out[30] = 0x02;
    out
}
