//! CRC-32 as the GPT specification uses it: the IEEE 802.3 polynomial,
//! reflected, initial value all ones, final complement. Firmware checks the
//! header and the entry array with exactly this; a disk with either wrong is
//! a disk with no partitions.

const POLY: u32 = 0xEDB8_8320;

pub fn crc32(data: &[u8]) -> u32 {
    let mut crc = 0xFFFF_FFFFu32;
    for &b in data {
        crc ^= b as u32;
        for _ in 0..8 {
            let mask = (crc & 1).wrapping_neg();
            crc = (crc >> 1) ^ (POLY & mask);
        }
    }
    !crc
}
