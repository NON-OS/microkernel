"""Render the chat window's glyphs: printable ASCII from JetBrains Mono.

    qwen-glyphs.py FONT.ttf PIXELS > glyphs.h

Each glyph is a cell of CELL_W x CELL_H coverage bytes, 0 to 255, from the
font's own antialiasing; the window blends them over its background. The
header is generated once and committed beside this script, so the guest
builds without a font renderer.
"""

import sys

from PIL import Image, ImageDraw, ImageFont


def main():
    font = ImageFont.truetype(sys.argv[1], int(sys.argv[2]))
    ascent, descent = font.getmetrics()
    cell_w = round(font.getlength("M"))
    cell_h = ascent + descent
    print("/* Generated by tools/qwen-glyphs.py from JetBrains Mono (OFL). */")
    print("#pragma once")
    print(f"enum {{ CELL_W = {cell_w}, CELL_H = {cell_h}, FIRST = 32, LAST = 126 }};")
    print("static const unsigned char GLYPHS[LAST - FIRST + 1][CELL_H][CELL_W] = {")
    for code in range(32, 127):
        img = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(img).text((0, 0), chr(code), font=font, fill=255)
        rows = []
        for y in range(cell_h):
            rows.append("{" + ",".join(str(img.getpixel((x, y))) for x in range(cell_w)) + "}")
        print("    {" + ",\n     ".join(rows) + "},")
    print("};")


if __name__ == "__main__":
    main()
