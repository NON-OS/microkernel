use super::layout::{FIRST_LINE_Y, LINE_HEIGHT};

pub(super) fn visible_rows(height: u32) -> u32 {
    height.saturating_sub(FIRST_LINE_Y).saturating_div(LINE_HEIGHT).max(1)
}
