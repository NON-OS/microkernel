//! EIP-712 field words. Every word is canonical for its type, as the keyring
//! requires: an address has twelve zero bytes in front, a uintN has its high
//! bytes zero. Building them here, and only here, keeps that one rule.

pub fn addr_word(a: &[u8; 20]) -> [u8; 32] {
    let mut w = [0u8; 32];
    w[12..].copy_from_slice(a);
    w
}

pub fn u64_word(v: u64) -> [u8; 32] {
    let mut w = [0u8; 32];
    w[24..].copy_from_slice(&v.to_be_bytes());
    w
}

/// A uint256 that holds a u128: amounts never need the top half.
pub fn u128_word(v: u128) -> [u8; 32] {
    let mut w = [0u8; 32];
    w[16..].copy_from_slice(&v.to_be_bytes());
    w
}
