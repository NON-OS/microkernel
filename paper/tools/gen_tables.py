#!/usr/bin/env python3
"""Write the LaTeX tables that come straight from the tree.

Run from the repository root:  python3 -I paper/tools/gen_tables.py
Reads userland/capsule_market/linux-catalogue.json and the driver capsule
directories; writes paper/sections/table-programs.tex, table-bits.tex and
table-drivers.tex. Nothing here is typed by hand.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "paper", "sections")

BITS = ["WAYLAND", "TTY", "FILES_HOME", "EXEC", "NET_ANON", "NET_LISTEN_LO", "JIT"]


def tex(s):
    return (s.replace("\\", "\\textbackslash{}").replace("_", "\\_")
             .replace("&", "\\&").replace("%", "\\%").replace("#", "\\#"))


def mono(s):
    return "\\texttt{" + tex(s) + "}"


cat = json.load(open(os.path.join(ROOT, "userland/capsule_market/linux-catalogue.json")))
apps = cat["apps"]
assert cat["format"] == "nonos.linux-catalogue.v1"

# Which programs draw a window, which run in the terminal, which are engines.
def group(a):
    m = a["mask"].split()
    if "WAYLAND" in m:
        return 0
    if "TTY" in m:
        return 1
    return 2

names = {0: "With a window of their own", 1: "In the Terminal", 2: "A background engine"}
rows = []
for g in (0, 1, 2):
    sel = [a for a in apps if group(a) == g]
    if not sel:
        continue
    rows.append("\\multicolumn{3}{@{}l}{\\textit{%s} (%d)}\\\\" % (names[g], len(sel)))
    for a in sel:
        box = " ".join(a["mask"].split())
        rows.append("%s & %s & %s\\\\" % (tex(a["name"]), mono(box), tex(a["licence"].replace(" WITH OpenSSL-Exception", " + exc."))))
    rows.append("\\addlinespace")
with open(os.path.join(OUT, "table-programs.tex"), "w") as f:
    f.write("% generated by paper/tools/gen_tables.py from linux-catalogue.json\n")
    f.write("{\\footnotesize\\setlength{\\tabcolsep}{4pt}\n")
    f.write("\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{3.6cm}>{\\raggedright\\arraybackslash}p{6.6cm}>{\\raggedright\\arraybackslash}p{4.2cm}@{}}\n")
    f.write("\\toprule Program & Its box & Licence\\\\ \\midrule\\endhead\n")
    f.write("\n".join(rows[:-1]) + "\n")
    f.write("\\bottomrule\n\\end{longtable}}\n")

# How many programs hold each right.
counts = {b: sum(1 for a in apps if b in a["mask"].split()) for b in BITS}
what = {
    "WAYLAND": "a window of its own on the desktop",
    "TTY": "the Terminal",
    "FILES_HOME": "its own home folder, and no other files",
    "EXEC": "starting other programs, each held to the same box",
    "NET_ANON": "outbound streams, over Nym or Anyone only",
    "NET_LISTEN_LO": "listening on the machine's own loopback",
    "JIT": "making code as it runs",
}
with open(os.path.join(OUT, "table-bits.tex"), "w") as f:
    f.write("% generated by paper/tools/gen_tables.py from linux-catalogue.json\n")
    f.write("\\begin{tabular}{@{}llr@{}}\n\\toprule Box word & What it lets the program have & Programs\\\\ \\midrule\n")
    for b in BITS:
        f.write("%s & %s & %d\\\\\n" % (mono(b), tex(what[b]), counts[b]))
    f.write("\\bottomrule\n\\end{tabular}\n")
with open(os.path.join(OUT, "numbers.tex"), "w") as f:
    f.write("\\newcommand{\\nPrograms}{%d}\n" % len(apps))
    for b in BITS:
        f.write("\\newcommand{\\n%s}{%d}\n" % (b.replace("_", ""), counts[b]))

# Driver classes, counted from the directory names against the README's grouping.
classes = [
    ("Storage", "ahci nvme piix_ide buslogic mpt pvscsi storvsc ufs sdhci rtsx virtio_blk virtio_scsi"),
    ("USB", "xhci ehci ohci uhci usb_hub usb_hid usb_msc usb_audio usb_mic uvc ccid fido cdc_acm cdc_ecm cdc_ncm rndis bt_usb"),
    ("Wired network", "e1000 e1000e igb igc ixgbe rtl8139 rtl8153 rtl8169 ax88179 pcnet tulip virtio_net vmxnet3 netvsc"),
    ("Wi-Fi", "iwlwifi mt7921 rtl8821ce rtl8822ce rtl8852be"),
    ("Input", "ps2_input i2c_hid spi_hid virtio_input vmmouse"),
    ("Display", "bga bootfb intel_display virtio_gpu vmware_svga"),
    ("Audio", "hda ac97"),
    ("Buses", "gpio i2c_pci spi smbus"),
    ("Virtual machine guests", "virtio_rng vmbus vmmdev"),
]
have = sorted(d[len("capsule_driver_"):] for d in os.listdir(os.path.join(ROOT, "userland"))
              if d.startswith("capsule_driver_")
              and os.path.isfile(os.path.join(ROOT, "userland", d, "Capsule.mk")))
listed = sorted(x for _, names_ in classes for x in names_.split())
assert have == listed, (set(have) ^ set(listed))
assert len(have) == 67
with open(os.path.join(OUT, "table-drivers.tex"), "w") as f:
    f.write("% generated by paper/tools/gen_tables.py from userland/capsule_driver_*/Capsule.mk\n")
    f.write("\\begin{tabular}{@{}lr>{\\raggedright\\arraybackslash}p{9.2cm}@{}}\n\\toprule Class & Count & Drivers\\\\ \\midrule\n")
    for c, n in classes:
        L = n.split()
        f.write("%s & %d & {\\footnotesize %s}\\\\\n" % (tex(c), len(L), ", ".join(mono(x) for x in L)))
    f.write("\\midrule Total & %d & \\\\\n\\bottomrule\n\\end{tabular}\n" % len(have))
print("ok", len(apps), counts, len(have))
