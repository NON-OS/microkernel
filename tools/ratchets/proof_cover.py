"""Which ring 0 lines a theorem over extracted code constrains.

Aeneas writes each extracted definition under a doc block naming its Rust
source and line range. A definition counts once a hand-written file (one
Aeneas did not generate) names it next to a theorem; its range then counts
wherever it holds code.
"""

import re
from pathlib import Path

BLOCK = re.compile(
    r"Source: '([^']+)', lines (\d+):\d+-(\d+):\d+.*?-/\s*(?:@\[[^\]]*\]\s*)*"
    r"(?:noncomputable\s+)?(?:def|structure|inductive|axiom)\s+([\w.']+)",
    re.S,
)
GENERATED = "THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS"


def extracted(lean_root):
    """{lean name: (kernel path under src/, first line, last line)}."""
    out = {}
    for p in lean_root.rglob("*.lean"):
        text = p.read_text(errors="ignore")
        if GENERATED not in text:
            continue
        for src, a, b, name in BLOCK.findall(text):
            if "/src/" in src and not src.startswith("/rustc"):
                rel = "src/" + src.rsplit("/src/", 1)[1]
                out[name] = (Path(rel), int(a), int(b))
    return out


def proved_names(lean_root, names):
    """Names a hand-written file with a theorem in it mentions in full."""
    texts = [p.read_text(errors="ignore") for p in lean_root.rglob("*.lean") if ".lake" not in p.parts]
    text = "\n".join(t for t in texts if GENERATED not in t and re.search(r"\btheorem\b", t))
    return {n for n in names if re.search(rf"(?<![\w.]){re.escape(n)}(?![\w'])", text)}


def covered(root, lean_root, kernel_files, code_line_numbers):
    """{kernel file: set of covered code lines}, restricted to ring 0."""
    ring0 = {f.resolve() for f in kernel_files}
    table = extracted(lean_root)
    out = {}
    for name in proved_names(lean_root, table):
        rel, a, b = table[name]
        f = (root / rel).resolve()
        if f in ring0:
            out.setdefault(f, set()).update(n for n in code_line_numbers(f) if a <= n <= b)
    return out
