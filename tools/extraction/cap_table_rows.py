"""Write the per-syscall refinement rows of the extracted capability table.

`CapTableRefinement` proves the extracted `cap_table::is_allowed` equal to the
model's `capTableAllows` for every syscall. One theorem per syscall, spread
over several modules, lets lake check them side by side; the closing theorem
then dispatches on the syscall to its row. The rows, the capability indices
and the tactic's unfolding set are read from the extracted Lean, and each
row's model entry from formal/Formal/Data/Syscalls.lean, so a syscall
or a capability added to the kernel changes these files, and --check fails
until they are written again and proved.
"""

import argparse
import re
import sys
from pathlib import Path

LEAN = Path('verification/extraction/lean')
OUT = LEAN / 'NonosExtraction'
CHUNK = 10

HEADER = '''/-
NONOS Operating System
Copyright (C) 2026 NONOS Contributors

This program is free software: you can redistribute it and/or modify it under
the terms of the GNU Affero General Public License as published by the Free
Software Foundation, either version 3 of the License, or (at your option) any
later version. See <https://www.gnu.org/licenses/>.

Generated by tools/extraction/cap_table_rows.py from CapTable/Types.lean and
CapTable/Funs.lean. Do not edit: run the script.
'''


def ctors(types, name):
    start = types.index('inductive %s where' % name)
    block = types[start:].split('\n\n', 1)[0]
    return re.findall(r'^\| (\w+) :', block, re.M)


def unfold_set(funs):
    names = re.findall(r'^def\s+([A-Za-z0-9_.]+)', funs, re.M)
    keep = [n for n in names
            if re.search(r'\.(can_[a-z_]+|reaches_network)$', n)
            or n.startswith('syscall.contract.cap_table.')
            or n == 'syscall.contract.is_allowed']
    return keep


def tactic_module(caps, unfold):
    lines = [HEADER + '''
The capability indices, read off the declaration order, and the tactic every
row runs: unfold the extracted table and the token checks down to membership
in the token's list, evaluate the model's table entry, and compare.
-/

import NonosExtraction.CapTableRefinementLemmas
open Aeneas Aeneas.Std Result

set_option linter.unusedSimpArgs false

namespace NonosExtraction.CapTable
open nonos_x_cap_table
''']
    for i, c in enumerate(caps):
        lines.append('@[simp] theorem idx_%s : idx .%s = %d := rfl' % (c, c, i))
    body = ',\n      '.join(unfold + [
        'grants_spec', 'grants_all_spec', 'lift', 'Array.make', 'Array.to_slice',
        'core.option.Option.or_else', 'bind_tc_ok', 'mem_holds',
        'Formal.Req.eval', 'has_word_holds', 'word_ne_zero_iff', 'Bool.and_assoc',
        'Bool.or_assoc'])
    lines.append('''
/-- One row: the extracted table against the model's entry, for a token
    whose validity is `is_valid_spec`. The row hands it the entry, checked
    against the model's table by `rfl`. -/
macro "cap_row" h:term "," hp:term : tactic =>
  `(tactic| (simp [%s, is_valid_spec _ $h, $hp:term] <;>
      first | rfl | ((repeat' split) <;>
        simp_all [List.isEmpty_iff])))

end NonosExtraction.CapTable
''' % body)
    return '\n'.join(lines)


def model_entries(root):
    text = (root / 'formal/Formal/Data/Syscalls.lean').read_text()
    body = text[text.index('def capTable'):]
    body = body[:body.index('\n]')]
    out = {}
    for m in re.finditer(r'^  \((\d+), (.+)\),? -- (\w+) \(', body, re.M):
        out[m.group(3)] = m.group(2)
    return out


def rows_module(k, names, entries):
    out = [HEADER + '''
Rows %d to %d of the capability table refinement.
-/

import NonosExtraction.CapTableRefinementTactic
open Aeneas Aeneas.Std Result

namespace NonosExtraction.CapTable
open nonos_x_cap_table

set_option maxHeartbeats 4000000
''' % (k * CHUNK, k * CHUNK + len(names) - 1)]
    for n in names:
        entry = 'some (%s : Formal.Req)' % entries[n] if n in entries else 'none'
        out.append('''theorem row_%s (t : Token) (h : t.expires_at_ms = none) (l : Bool) :
    syscall.contract.is_allowed t .%s l =
      ok (Formal.capTableAllows (word t.permissions.val) l (tag .%s)) := by
  have e : Formal.lookupReq (tag .%s) = %s := rfl
  simp only [Formal.capTableAllows, e]
  %sby_cases hp : t.permissions.val = [] <;> cap_row h, hp
''' % (n, n, n, n, entry, 'cases l <;> ' if '.launcher' in entry else ''))
    out.append('end NonosExtraction.CapTable\n')
    return '\n'.join(out)


def closing_module(nchunks, syscalls):
    imports = '\n'.join('import NonosExtraction.CapTableRefinementRows%d' % k for k in range(nchunks))
    arms = '\n'.join('  | .%s => row_%s t h l' % (n, n) for n in syscalls)
    return HEADER + '''
The extracted capability table is the model's. For every syscall and every
token with no expiry (every process token, `process::caps::new_token`), the
kernel's `cap_table::is_allowed`, translated by Aeneas from the Rust, returns
exactly what `Formal.capTableAllows` computes on the token's word. The model's
table is generated from the same Rust by formal/scripts/gen_tables.py; this
theorem replaces trust in that generator with a proof, entry by entry.
-/

import CapTable.Funs
%s
open Aeneas Aeneas.Std Result

namespace NonosExtraction.CapTable
open nonos_x_cap_table

/-- **The capability table refines the model.** -/
theorem is_allowed_is_the_model (t : Token) (h : t.expires_at_ms = none) (n : Sys) (l : Bool) :
    syscall.contract.is_allowed t n l =
      ok (Formal.capTableAllows (word t.permissions.val) l (tag n)) :=
  match n with
%s

end NonosExtraction.CapTable

/-! ### Axiom profile -/

#print axioms NonosExtraction.CapTable.is_allowed_is_the_model
#print axioms NonosExtraction.CapTable.bit_is_two_pow
#print axioms NonosExtraction.CapTable.grants_spec
#print axioms NonosExtraction.CapTable.grants_all_spec
#print axioms NonosExtraction.CapTable.is_valid_spec
''' % (imports, arms)


def render(root):
    types = (root / LEAN / 'CapTable/Types.lean').read_text()
    funs = (root / LEAN / 'CapTable/Funs.lean').read_text()
    caps = ctors(types, 'capabilities.types.defs.Capability')
    syscalls = ctors(types, 'syscall.numbers.defs.SyscallNumber')
    chunks = [syscalls[i:i + CHUNK] for i in range(0, len(syscalls), CHUNK)]
    entries = model_entries(root)
    files = {OUT / 'CapTableRefinementTactic.lean': tactic_module(caps, unfold_set(funs))}
    for k, names in enumerate(chunks):
        files[OUT / ('CapTableRefinementRows%d.lean' % k)] = rows_module(k, names, entries)
    files[OUT / 'CapTableRefinement.lean'] = closing_module(len(chunks), syscalls)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n', 1)[0])
    ap.add_argument('--root', type=Path, default=Path('.'))
    ap.add_argument('--check', action='store_true', help='fail if a file differs')
    a = ap.parse_args()
    root = a.root.resolve()
    files = render(root)
    stale = sorted(str(p) for p in (root / OUT).glob('CapTableRefinementRows*.lean')
                   if p.relative_to(root) not in files)
    bad = []
    for rel, text in files.items():
        path = root / rel
        if a.check:
            if not path.is_file() or path.read_text() != text:
                bad.append(str(rel))
        else:
            path.write_text(text)
    if a.check and (bad or stale):
        for b in bad + stale:
            print('cap_table_rows: %s is not what the extracted table gives' % b, file=sys.stderr)
        return 1
    if not a.check:
        for s in stale:
            Path(s).unlink()
    return 0


if __name__ == '__main__':
    sys.exit(main())
