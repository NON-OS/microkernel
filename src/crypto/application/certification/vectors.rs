//! The published answers the self test checks against.
//!
//! Every byte here is the same vector `userland/crypto_proofs` asserts in CI,
//! which is where they were verified. They are restated rather than shared
//! because the proof crates build for the host and this builds for the
//! machine; if the two ever disagree, one of them is wrong and the CI crate is
//! the one that has been checked against the standards text.
//!
//! A test without one of these is not a known-answer test. It was worth
//! writing that down: six of the seven checks in this directory used to
//! generate their own input, run it through the algorithm and back, and
//! compare the result with what they started from, which any self-consistently
//! wrong implementation also satisfies.

