extern crate alloc;

use alloc::vec::Vec;

pub(super) fn directions_from_index(mut index: usize, depth: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(depth);
    for _ in 0..depth {
        out.push((index & 1) as u8);
        index >>= 1;
    }
    out
}
