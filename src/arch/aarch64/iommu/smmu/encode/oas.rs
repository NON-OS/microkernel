//! The 3-bit address-size codes OAS and IPS share.

/// Address bits an OAS or IPS code stands for.
pub const fn oas_bits(code: u8) -> u8 {
    match code {
        0 => 32,
        1 => 36,
        2 => 40,
        3 => 42,
        4 => 44,
        5 => 48,
        _ => 52,
    }
}
