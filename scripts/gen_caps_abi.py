"""Emit the [bits] section of the capability ABI from the kernel table.

Written rather than maintained, because a hand kept copy of a table is a second
answer to a question that already has one, and the two only have to disagree
once for a toolchain to grant a permission nobody asked for.

Only [bits] is generated. Groups and delegation are policy: which capabilities
belong together is a decision, not a fact derivable from the enum, so this
prints them back unchanged and reports any name they use that no longer
resolves.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from check_caps_abi import read_kernel, sections  # noqa: E402

ABI_CAPS = Path("abi/caps.toml")
HEADER = ("# Generated by scripts/gen_caps_abi.py from\n"
          "# src/capabilities/types/defs.rs. Do not edit [bits] by hand.\n")


def screaming(name: str) -> str:
    """CamelCase to the SCREAMING_SNAKE the rest of the ABI files use.

    A run of capitals is one word, so `IPC` stays `IPC` rather than becoming
    `I_P_C`, and `GraphicsDisplayQuery` still separates on each word.
    """
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])",
                  "_", name).upper()


def emit_bits(kernel) -> str:
    rows = sorted(((n, b) for n, b in kernel.values()), key=lambda kv: kv[1])
    width = max(len(screaming(n)) for n, _ in rows)
    out = ["[bits]"]
    for name, bit in rows:
        grouped = f"{bit:016X}"
        pretty = "_".join(grouped[i:i + 4] for i in range(0, 16, 4))
        out.append(f"{screaming(name):<{width}} = 0x{pretty}")
    return "\n".join(out) + "\n"


BITS_ROW = re.compile(r"[A-Z0-9_]+ *= *0x[0-9A-Fa-f_]+$")


def replace_bits(text: str, bits: str) -> str:
    """`text` with its [bits] table, and the header that names its source,
    replaced by `bits`; every other line kept as it was.

    The section is found as a line of its own: the header's own words name
    [bits], and splitting on the first "[bits]" anywhere once wrote the table
    in the middle of the header and kept the old one after it.
    """
    m = re.search(r"^\[bits\]\n", text, re.M)
    if m is None:
        return text.rstrip("\n") + "\n\n" + HEADER + bits
    head = text[:m.start()]
    if head.endswith(HEADER):
        head = head[:-len(HEADER)]
    rows = text[m.end():].split("\n")
    kept = 0
    while kept < len(rows) and BITS_ROW.match(rows[kept]):
        kept += 1
    tail = "\n".join(rows[kept:])
    return head + HEADER + bits + tail


def self_test() -> int:
    """Writing over a current table changes nothing, twice; a missing or
    wrong row comes back; a file with no table gets one."""
    bits = "[bits]\nA = 0x0000_0000_0000_0001\nBB = 0x0000_0000_0000_0002\n"
    doc = "version = 1\n\n" + HEADER + bits + "\n# Bundles.\n[groups]\nG = [\"A\"]\n"
    stale = doc.replace("BB = 0x0000_0000_0000_0002\n", "")
    wrong = doc.replace("0x0000_0000_0000_0002", "0x0000_0000_0000_0004")
    cases = [
        ("current", replace_bits(doc, bits) == doc),
        ("twice", replace_bits(replace_bits(doc, bits), bits) == doc),
        ("a row missing", replace_bits(stale, bits) == doc),
        ("a row wrong", replace_bits(wrong, bits) == doc),
        ("no table", replace_bits("version = 1\n", bits) == "version = 1\n\n" + HEADER + bits),
    ]
    bad = [name for name, ok in cases if not ok]
    print(f"gen-caps-abi self-test: {len(cases)} cases, {len(bad)} wrong {bad if bad else ''}")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=Path("."), help="repository root")
    ap.add_argument("--write", action="store_true",
                    help="replace [bits] in abi/caps.toml instead of printing it")
    ap.add_argument("--self-test", action="store_true", help="check the rewrite and exit")
    args = ap.parse_args()
    if args.self_test:
        return self_test()

    try:
        kernel = read_kernel(args.root)
        text = (args.root / ABI_CAPS).read_text()
    except FileNotFoundError as e:
        print(f"gen-caps-abi: {e}", file=sys.stderr)
        return 2

    published = {screaming(n) for n, _ in kernel.values()}
    stale = set()
    for group in ("groups", "delegation"):
        for _, raw in sections(text).get(group, []):
            stale.update(n for n in re.findall(r'"([^"]+)"', raw)
                         if n not in published)

    bits = emit_bits(kernel)
    if not args.write:
        print(HEADER + bits, end="")
    else:
        (args.root / ABI_CAPS).write_text(replace_bits(text, bits))
        print(f"gen-caps-abi: wrote {len(kernel)} bits to {ABI_CAPS}")

    if stale:
        print(f"gen-caps-abi: {len(stale)} names used by groups no longer exist: "
              + ", ".join(sorted(stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
